REFINED = dict(recov_en=1, sweep_persist=1, starve_en=1)          # all Step-1 features ON (other values = documented defaults)
def refined(**kw): return Params(**{**REFINED, **kw})

def make_trace(n, active_fn, act=None, urg=None):
    """active_fn(t)->0/1 ; act/urg: per-block lists or fn(t)->list."""
    tr = []
    for t in range(n):
        a = active_fn(t); ac = act(t) if callable(act) else (act or [2] * NB); ur = urg(t) if callable(urg) else (urg or [0] * NB)
        tr.append(dict(tick=t, phase="ACTIVE" if a else "IDLE", mission_active=int(a), act=list(ac), urg=list(ur)))
    return tr

def run_closed_loop(params, trace, faults=None):
    """faults: {block: (start_tick, end_tick)} persistent fault; a decision whose tests include a scan/DIAG component on that block
    fails (reported to the Manager on the next tick via res_fail).  Returns (decision dicts, fail-event dict tick->mask)."""
    faults = faults or {}; m = Manager(params); out = []; fe = {}; res = [0] * NB; stats = load_stats()
    for x in trace:
        t = x["tick"]
        if any(res): fe[t] = sum(1 << b for b in range(NB) if res[b])
        d = m.step(x["mission_active"], x["act"], x["urg"], res); out.append(d); res = [0] * NB
        if d["valid"]:
            for name, b, cy in components(d["blk"], d["tset"], stats):
                if name in ("FULL_SCAN", "PARTIAL_SCAN", "DIAG") and b in faults and faults[b][0] <= t < faults[b][1]: res[b] = 1
    return out, fe

def first(seq, pred):
    for i, x in enumerate(seq):
        if pred(x): return i
    return None

# ---------------------------------------------------------------- RTL
def build_rtl(tag, p: Params):
    """Copy the reliability RTL into build/step1_rtl/<tag>/, write a refine-params header for Params p, compile tb_scheduler_step1."""
    d = f"{BUILD}/step1_rtl/{tag}"; os.makedirs(d, exist_ok=True)
    for f in ("state_monitor", "aging_model", "health_manager", "priority_engine", "test_scheduler", "reliability_manager"):
        shutil.copy(f"{RTL}/reliability/{f}.sv", d)
    open(f"{d}/rel_params.svh", "w").write(rtl_header(p, None))
    open(f"{d}/rel_refine_params.svh", "w").write(refine_header(p))
    srcs = [f"{d}/{f}.sv" for f in ("state_monitor", "aging_model", "health_manager", "priority_engine", "test_scheduler", "reliability_manager")]
    r = subprocess.run(["iverilog", "-g2012", "-I", d, "-o", f"{d}/tb.vvp", f"{ROOT}/tb/tb_scheduler_step1.sv"] + srcs, capture_output=True, text=True)
    if r.returncode: raise RuntimeError(r.stderr)
    return f"{d}/tb.vvp"

def refine_header(p: Params):
    return "\n".join(["// generated by python/step1_lib.py"] + [f"localparam {n}_P = {v};" for n, v in
        (("REC_EN", p.recov_en), ("REC_N", p.recov_n), ("MARGIN", p.reentry_margin), ("SWEEP_PERSIST", p.sweep_persist),
         ("STARVE_EN", p.starve_en), ("OVERDUE_T", p.overdue_ticks), ("FAIR_GAP", p.fair_gap),
         ("EVID_EN", p.evid_en), ("ARISK_DEG", p.arisk_deg),
         ("OBS_EN", p.obs_en), ("ESC_EN", p.esc_en), ("ESC_GAP", p.esc_gap), ("STALE_EN", p.stale_en))]) + "\n"

def write_mem(tr, path, fe=None, fc=None):
    """fc: Step-3 failing-class events {tick: packed 20-bit word, 4 bits per block}.  Always written (112-bit trace words)."""
    fe = fe or {}; mission.write(tr, None, path, fe, fc if fc is not None else {})

def pack_cls(cls_by_block):
    """{block: class mask} -> packed 20-bit word"""
    return sum((c & 0xF) << (4 * b) for b, c in cls_by_block.items())

def run_rtl(vvp, mem, out, mode, ticks, rst_at=-1):
    args = ["vvp", vvp, f"+trace={mem}", f"+out={out}", f"+mode={mode}", f"+ticks={ticks}"] + ([f"+rst_at={rst_at}"] if rst_at >= 0 else [])
    r = subprocess.run(args, capture_output=True, text=True)
    if "done" not in r.stdout: raise RuntimeError(r.stdout + r.stderr)
    return [list(map(int, l.split(","))) for l in open(out)]

def expected_row(i, d):
    return ([i, d["state"], d["valid"], d["blk"], d["tset"], d["reason"], d["degmask"]] + d["prio"] + d["health"] + d["aging"] + d["faults"] +
            [d["unres"]] + d["okc"] + [d["ackv"]] + d["ack"] + [d["sweep"], d["gap"], d["fair"]] + d["lastfull"] + [d["overdue"]] +
            [d["arisk"], d["dfault"], d["aflag"], d["fcause"], d["nf"], d["esc"], d["lfstale"]])

COLS = (["tick", "state", "valid", "blk", "tset", "reason", "degmask"] + [f"prio{b}" for b in range(5)] + [f"health{b}" for b in range(5)] +
        [f"aging{b}" for b in range(5)] + [f"faults{b}" for b in range(5)] + ["unres"] + [f"okc{b}" for b in range(5)] + ["ackv"] +
        [f"ack{b}" for b in range(5)] + ["sweep", "gap", "fair"] + [f"lastfull{b}" for b in range(5)] + ["overdue", "arisk", "dfault", "aflag", "fcause", "nf", "esc", "lfstale"])

def python_trace(p, trace, fe, rst_at=-1, fc=None):
    m = Manager(p); out = []; fc = fc or {}
    for i, x in enumerate(trace):
        if i == rst_at: m = Manager(p)
        res = [(fe.get(i, 0) >> b) & 1 for b in range(NB)]; w = fc.get(i, 0); rc = [(w >> (4 * b)) & 0xF for b in range(NB)]
        out.append(m.step(x["mission_active"], x["act"], x["urg"], res, rc))
    return out

def compare(p, trace, fe, tag, mode=0, rst_at=-1, vvp=None, keep=None, fc=None):
    """Full per-tick comparison of decision + all internal state columns. Returns (n_ticks, n_mismatch, first_mismatch_str)."""
    vvp = vvp or build_rtl(tag, p); os.makedirs(f"{BUILD}/step1", exist_ok=True)
    mem = f"{BUILD}/step1/{tag}.mem"; write_mem(trace, mem, fe, fc)
    rtl = run_rtl(vvp, mem, f"{BUILD}/step1/{tag}_rtl.csv", mode, len(trace), rst_at)
    pm = replace(p, mode=mode); py = python_trace(pm, trace, fe, rst_at, fc); bad = 0; msg = ""
    for i, d in enumerate(py):
        e = expected_row(i, d)
        if e != rtl[i]:
            bad += 1
            if not msg: msg = f"tick {i}: " + ", ".join(f"{COLS[k]} py={e[k]} rtl={rtl[i][k]}" for k in range(len(e)) if e[k] != rtl[i][k])
    return len(py), bad, msg

# ---------------------------------------------------------------- analysis
FULLMASK = (1 << NB) - 1
def block_counts(dlog):
    """Per-block FULL / PARTIAL scan counts from decisions (an ALLBLK baseline decision counts for every block)."""
    full = [0] * NB; part = [0] * NB; last = [None] * NB
    for d in dlog:
        if not d["valid"]: continue
        for b in (range(NB) if d["blk"] == ALLBLK else [d["blk"]]):
            if d["tset"] & FULL: full[b] += 1; last[b] = d["tick"]
            if d["tset"] & PARTIAL: part[b] += 1
    return full, part, last

def mode_time(dlog): 
    c = [0, 0, 0]
    for d in dlog: c[d["state"]] += 1
    return dict(zip(SNAMES, c))

FCAUSE = {0: "not_degraded", 1: "no_window_mission_active", 2: "starve_en_off", 3: "fair_gap_not_elapsed",
          4: "withheld_by_unresolved_diagnostic", 5: "no_overdue_unflagged_candidate", 6: "granted"}

def starvation_report(dlog, trace, p, final_tick=None):
    """Per-block starvation classification at the end of the run (or final_tick), supported by the decision log (Step-2A rewrite).
    v1/Step-1 used ONE global condition (any flagged block holding unresolved evidence) for every overdue block.  Here a block is
    reported as withheld by a diagnostic ONLY if at least one tick since its last full scan (a) was a mission-idle window, (b) the block
    was an overdue, unflagged fairness candidate, (c) the fair gap had elapsed and (d) the scheduler recorded fcause==4 (an unresolved
    diagnostic on another flagged block took the slot).  fcause is recorded by the scheduler itself (RTL dbg_fcause == Python 'fcause');
    evidence_source says 'recorded' if the log carries it, else the class is 'UNVERIFIED_INFERRED_*' (trace-only inference).
    Classes (precedence order):
      OK                                           not overdue at the final tick
      STARVED_NO_ELIGIBLE_WINDOW                   overdue, zero mission-idle ticks since last full scan
      OVERDUE_BLOCK_HAS_UNRESOLVED_DIAGNOSTIC      overdue block is itself flagged with unresolved fault evidence (its own diagnostic has the slot by design)
      WITHHELD_BY_UNRESOLVED_DIAGNOSTIC            >=1 recorded tick where an unresolved diagnostic on another block took the fairness slot
      OVERDUE_FEATURE_DISABLED                     windows existed in DEGRADED but starve_en is off (scheduler records fcause 2)
      OVERDUE_WAITING_FAIR_GAP                     windows existed in DEGRADED but the fair gap had not elapsed
      OVERDUE_SERVED_ELSEWHERE_OR_PENDING          windows used for other full scans (sweep / fairness grants) - block still pending its turn
      OVERDUE_ELIGIBLE_WINDOWS_AVAILABLE_BUT_UNUSED  none of the recorded causes explains it (should be empty in a consistent log)"""
    full, part, last = block_counts(dlog); T = final_tick if final_tick is not None else len(dlog) - 1; rec = "fcause" in dlog[0]; rep = []
    for b in range(NB):
        lf16 = dlog[T]["lastfull"][b]; since = (T - lf16) & 0xFFFF; lf = T - since      # lastfull is a 16-bit tick stamp; true tick recovered from the modular age
        win_ticks = [t for t in range(lf + 1, T + 1) if not trace[t]["mission_active"]]
        win = len(win_ticks)
        unres_T = [BNAMES[k] for k in range(NB) if dlog[T]["unres"] >> k & 1 and dlog[T]["degmask"] >> k & 1]
        c = dict(withheld=0, gap=0, off=0, served=0, by=set())
        for t in win_ticks:
            d = dlog[t]
            cand_b = (d["overdue"] >> b & 1) and not (d["degmask"] >> b & 1)
            if d["valid"] and d["blk"] != b and d["tset"] & FULL and d["reason"] in (1, 5): c["served"] += 1
            if d["state"] == ST_DEG and cand_b and rec:
                fc = d.get("fcause", 0)
                if fc == 4:
                    c["withheld"] += 1; c["by"].update(BNAMES[k] for k in range(NB) if d["unres"] >> k & 1 and d["degmask"] >> k & 1)
                elif fc == 3: c["gap"] += 1
                elif fc == 2: c["off"] += 1
        self_unres = bool(dlog[T]["unres"] >> b & 1 and dlog[T]["degmask"] >> b & 1)
        if since < p.overdue_ticks: cls = "OK"
        elif win == 0: cls = "STARVED_NO_ELIGIBLE_WINDOW"
        elif self_unres: cls = "OVERDUE_BLOCK_HAS_UNRESOLVED_DIAGNOSTIC"
        elif not rec:
            cls = "UNVERIFIED_INFERRED_WITHHELD" if (dlog[T]["unres"] & dlog[T]["degmask"]) else "OVERDUE_ELIGIBLE_WINDOWS_AVAILABLE_BUT_UNUSED"
        elif c["withheld"]: cls = "WITHHELD_BY_UNRESOLVED_DIAGNOSTIC"
        elif c["off"]: cls = "OVERDUE_FEATURE_DISABLED"
        elif c["gap"]: cls = "OVERDUE_WAITING_FAIR_GAP"
        elif c["served"]: cls = "OVERDUE_SERVED_ELSEWHERE_OR_PENDING"
        else: cls = "OVERDUE_ELIGIBLE_WINDOWS_AVAILABLE_BUT_UNUSED"
        rep.append(dict(block=BNAMES[b], last_full_tick=lf, ticks_since_full=since, eligible_windows_since=win, overdue=int(since >= p.overdue_ticks),
                        classification=cls, unresolved_diagnostic_blocks_at_end=unres_T, block_itself_unresolved=int(self_unres),
                        window_ticks_withheld_by_diag=c["withheld"], window_ticks_fair_gap=c["gap"], window_ticks_feature_off=c["off"],
                        window_ticks_served_other_block=c["served"], withholding_blocks=sorted(c["by"]),
                        evidence_source="recorded(fcause)" if rec else "inferred_from_trace"))
    return rep
